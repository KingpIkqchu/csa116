        System.out.println("Original value: " + val3);
        updval3 = val3 * 2;
        updval3 = updval3 + 6;
        updval3 = updval3 / 2;
        updval3 = updval3 - val3;

        System.out.println(updval3);
    
    // 1 - Tiger
        int val4 = 1;
